// Pairing: which board (deviceId) this project may push firmware to, and the bearer token
// that proves it (_config/architecture.md → Track D → "Pairing"). The token only ever reaches
// the editor through a physical channel: the Improv *provisioned URL*
// `https://<editor>/pair?device=<deviceId>&token=<token>`, returned over BLE or the USB cable
// at the end of provisioning. It is stored in the project record (IndexedDB), never in plain
// localStorage, never in a URL after the pairing is read, and never in a log line.

/** What a project keeps about the board it is paired with. */
export interface WifiPairing {
  /** The chip's base MAC, lower-case hex without separators (12 chars). */
  deviceId: string;
  /** 32 random bytes as hex, generated by the board; sent as `Authorization: Bearer`. */
  token: string;
  /** Display name (from Improv or the relay); never used for anything but showing it. */
  name: string;
  /** The relay this pairing talks to (the editor's relay at pairing time). */
  relayUrl: string;
}

export const RELAY_URL_STORAGE_KEY = 'som.relayUrl';
/** The deployed relay (server/relay, Fly app som-relay); `VITE_RELAY_URL` overrides it. */
export const FALLBACK_RELAY_URL = 'https://som-relay.fly.dev';

/** Same shapes the relay accepts (server/relay/src/app.ts, auth.ts). */
const DEVICE_ID_RE = /^[0-9a-f]{12}$/;
const TOKEN_RE = /^[0-9a-fA-F]{32,128}$/;
const MAX_NAME = 64;

export function isDeviceId(value: unknown): value is string {
  return typeof value === 'string' && DEVICE_ID_RE.test(value);
}

export function isPairingToken(value: unknown): value is string {
  return typeof value === 'string' && TOKEN_RE.test(value);
}

/** A printable, bounded device name; falls back to `placa-<last 4 of the MAC>`. */
export function deviceName(name: unknown, deviceId: string): string {
  // Control characters out (a name is shown, never interpreted), then trimmed and bounded.
  const printable =
    typeof name === 'string'
      ? [...name].filter((c) => c.charCodeAt(0) >= 0x20 && c.charCodeAt(0) !== 0x7f).join('')
      : '';
  const cleaned = printable.trim().slice(0, MAX_NAME);
  return cleaned || `placa-${deviceId.slice(-4)}`;
}

/** Checks a stored value (IndexedDB is untrusted input after an import or a bug). */
export function toPairing(value: unknown): WifiPairing | null {
  if (typeof value !== 'object' || value === null) return null;
  const v = value as Partial<Record<keyof WifiPairing, unknown>>;
  if (!isDeviceId(v.deviceId) || !isPairingToken(v.token)) return null;
  if (typeof v.relayUrl !== 'string' || !/^https?:\/\//.test(v.relayUrl)) return null;
  return {
    deviceId: v.deviceId,
    token: v.token,
    name: deviceName(v.name, v.deviceId),
    relayUrl: v.relayUrl,
  };
}

/** The relay the editor talks to: saved override > `VITE_RELAY_URL` > the deployed relay. */
export function defaultRelayUrl(): string {
  try {
    const stored = window.localStorage.getItem(RELAY_URL_STORAGE_KEY)?.trim();
    if (stored) return stored.replace(/\/+$/, '');
  } catch {
    // Storage blocked: use the build's relay.
  }
  const fromEnv = (import.meta.env.VITE_RELAY_URL as string | undefined)?.trim();
  return (fromEnv || FALLBACK_RELAY_URL).replace(/\/+$/, '');
}

/** `device` + `token` (+ optional `name`) from a pairing link, or null when not one. */
export interface PairingParams {
  deviceId: string;
  token: string;
  name?: string;
}

/**
 * Reads the pairing from a provisioned URL (`…/pair?device=…&token=…`). The origin is not
 * checked: a board provisioned against the production editor still pairs with a local one,
 * and nothing but `device`, `token` and `name` is taken from it (never a relay address, so a
 * crafted link cannot send the student's programs elsewhere).
 */
export function parsePairingUrl(raw: string, base?: string): PairingParams | null {
  let url: URL;
  try {
    url = new URL(raw, base);
  } catch {
    return null;
  }
  if (!/\/pair\/?$/.test(url.pathname)) return null;
  const deviceId = url.searchParams.get('device')?.toLowerCase();
  const token = url.searchParams.get('token');
  if (!isDeviceId(deviceId) || !isPairingToken(token)) return null;
  const name = url.searchParams.get('name');
  return { deviceId, token, ...(name ? { name } : {}) };
}

/**
 * Called once at startup, before anything renders: takes a pairing link out of the address
 * bar (so the token never stays in the URL, the history entry or a bookmark) and returns
 * it. `/pair` becomes the app root it lives under; other query parameters (`?lang=`) stay.
 * A `/pair` address without valid parameters is cleaned up the same way.
 */
export function takePairingFromLocation(
  location: Pick<Location, 'href'> = window.location,
  history: Pick<History, 'replaceState' | 'state'> = window.history,
): PairingParams | null {
  const url = new URL(location.href);
  const onPairPath = /\/pair\/?$/.test(url.pathname);
  const hasParams = url.searchParams.has('device') || url.searchParams.has('token');
  if (!onPairPath && !hasParams) return null;
  const pairing = onPairPath ? parsePairingUrl(url.href) : null;
  url.searchParams.delete('device');
  url.searchParams.delete('token');
  url.searchParams.delete('name');
  if (onPairPath) url.pathname = url.pathname.replace(/pair\/?$/, '');
  history.replaceState(history.state, '', url);
  return pairing;
}

/** The record a project stores for a pairing made now against the editor's relay. */
export function newPairing(params: PairingParams, relayUrl = defaultRelayUrl()): WifiPairing {
  return {
    deviceId: params.deviceId,
    token: params.token,
    name: deviceName(params.name, params.deviceId),
    relayUrl,
  };
}
